/**
 * Writes theme.css from src/theme.css and the mistpine spec.
 *
 *   pnpm generate          write theme.css
 *   pnpm generate --check  fail if theme.css is out of date
 *
 * It also checks the result against Obsidian's theme rules: no remote
 * assets, no @import and no !important.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { hsl, loadSpec, mix, ROOT, rgb, type Spec } from "./lib/colors.ts";

const check = process.argv.includes("--check");
const { spec, source } = await loadSpec();
const manifest = JSON.parse(readFileSync(join(ROOT, "manifest.json"), "utf8")) as {
  name: string;
  version: string;
};

/** A palette key (`bg1`) or a spec token (`syntax.comment`, `ui.accent`). */
function color(key: string): string {
  const [group, name] = key.includes(".") ? key.split(".", 2) : ["palette", key];
  const table = spec[group as keyof Spec] as Record<string, unknown> | undefined;
  const value = table?.[name as string];
  const hex = typeof value === "string" ? value : (value as { hex?: string } | undefined)?.hex;
  if (!hex) throw new Error(`src/theme.css: the spec has no color ${key}`);
  return hex;
}

/** Recomputes the spec's own blends, so `mix` provably matches the spec. */
function verifyBlends(): void {
  const names: Record<string, string> = { "@terminal.background": color("terminal.background") };
  let checked = 0;
  for (const [name, token] of Object.entries(spec.ui)) {
    if (!token.derived) continue;
    const m = token.derived.match(/^mix\((\S+), \$(\w+), (\d+)%\)$/);
    if (!m) throw new Error(`ui.${name}: unknown blend ${token.derived}`);
    const [, base, key, pct] = m as unknown as [string, string, string, string];
    const got = mix(names[base] ?? color(base.replace(/^\$/, "")), color(key), Number(pct) / 100);
    if (got !== token.hex)
      throw new Error(`mix for ui.${name} gives ${got}, spec says ${token.hex}`);
    checked++;
  }
  // The spec has blends; finding none means its format changed under us.
  if (checked === 0) throw new Error("the spec has no blends: did its format change?");
}

function expand(template: string): string {
  return template.replace(/\{\{([^}]+)\}\}/g, (_, raw: string) => {
    const parts = raw.trim().split(":");
    switch (parts.length === 1 ? "color" : parts[0]) {
      case "color":
        return color(parts[0] as string);
      case "rgb":
        return rgb(color(parts[1] as string))
          .map((v) => Math.round(v * 255))
          .join(", ");
      case "mix": {
        const [, base, over, pct] = parts as [string, string, string, string];
        if (parts.length !== 4 || !/^\d+$/.test(pct)) throw new Error(`bad token {{${raw}}}`);
        return mix(color(base), color(over), Number(pct) / 100);
      }
      case "h":
      case "s":
      case "l":
        return String(hsl(color(parts[1] as string))["hsl".indexOf(parts[0] as string)]);
      default:
        throw new Error(`unknown token {{${raw}}}`);
    }
  });
}

function lint(css: string): void {
  const problems = [
    [/!important/, "!important stops users overriding the theme with snippets"],
    [/@import/, "@import loads remote CSS"],
    [/url\(\s*["']?(?!data:)/, "url() must be a data: URL (no network in directory themes)"],
    [/\{\{|\}\}/, "unexpanded template token"],
  ] as const;
  for (const [re, why] of problems) {
    const at = css.search(re);
    if (at >= 0) {
      const line = css.slice(0, at).split("\n").length;
      throw new Error(`theme.css:${line}: ${why}`);
    }
  }
}

verifyBlends();
const template = readFileSync(join(ROOT, "src", "theme.css"), "utf8");
// The template's own header documents tokens; the output gets its own.
const body = template.replace(/^\/\*[\s\S]*?\*\/\n+/, "");
const header = `/*
 * ${manifest.name} ${manifest.version}: the mistpine color scheme for Obsidian.
 * https://github.com/mistpine/mistpine.obsidian · MIT License
 *
 * Generated by scripts/generate.ts from src/theme.css and the mistpine spec
 * (https://github.com/mistpine/mistpine/blob/main/palette/mistpine.json).
 * Do not edit by hand.
 */

`;
const css = header + expand(body);
lint(css);

const out = join(ROOT, "theme.css");
if (check) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== css) {
    console.error("theme.css is out of date: run pnpm generate");
    process.exit(1);
  }
  console.log(`theme.css is up to date (spec: ${source})`);
} else {
  writeFileSync(out, css);
  console.log(`wrote theme.css (spec: ${source})`);
}
